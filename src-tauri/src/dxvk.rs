#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_default_config() {
        let config = generate_config("skyrimse", &DxvkPreset::Default, &HashMap::new());
        assert!(config.contains("dxvk.enableGraphicsPipelineLibrary = False"));
        assert!(config.contains("Generated by Corkscrew"));
    }

    #[test]
    fn test_performance_preset() {
        let config = generate_config("skyrimse", &DxvkPreset::Performance, &HashMap::new());
        assert!(config.contains("dxvk.enableAsync = True"));
    }

    #[test]
    fn test_compatibility_preset() {
        let config = generate_config("skyrimse", &DxvkPreset::Compatibility, &HashMap::new());
        assert!(config.contains("dxvk.enableGraphicsPipelineLibrary = False"));
        assert!(config.contains("dxvk.enableAsync = False"));
    }

    #[test]
    fn test_custom_overrides() {
        let mut custom = HashMap::new();
        custom.insert("dxvk.enableAsync".to_string(), "True".to_string());
        let config = generate_config("skyrimse", &DxvkPreset::Default, &custom);
        // Custom override should win
        assert!(config.contains("dxvk.enableAsync = True"));
    }

    #[test]
    fn test_game_specific_overrides() {
        let overrides = get_game_overrides("skyrimse");
        assert!(overrides.contains_key("dxvk.enableGraphicsPipelineLibrary"));
    }

    #[test]
    fn test_deploy_config() {
        let dir = tempfile::tempdir().unwrap();
        let result = deploy_config(
            dir.path(),
            "skyrimse",
            &DxvkPreset::Default,
            &HashMap::new(),
        );
        assert!(result.is_ok());
        let path = result.unwrap();
        assert!(path.exists());
        let content = std::fs::read_to_string(&path).unwrap();
        assert!(content.contains("dxvk.enableGraphicsPipelineLibrary = False"));
    }

    #[test]
    fn test_deploy_config_idempotent() {
        let dir = tempfile::tempdir().unwrap();
        let path1 = deploy_config(
            dir.path(),
            "skyrimse",
            &DxvkPreset::Default,
            &HashMap::new(),
        )
        .unwrap();
        let mtime1 = std::fs::metadata(&path1).unwrap().modified().unwrap();

        // Small sleep to ensure mtime would differ if file were rewritten
        std::thread::sleep(std::time::Duration::from_millis(50));

        let path2 = deploy_config(
            dir.path(),
            "skyrimse",
            &DxvkPreset::Default,
            &HashMap::new(),
        )
        .unwrap();
        let mtime2 = std::fs::metadata(&path2).unwrap().modified().unwrap();

        // File should NOT have been rewritten (same content)
        assert_eq!(mtime1, mtime2);
    }

    #[test]
    fn test_unknown_game_no_crash() {
        let config = generate_config("unknown_game", &DxvkPreset::Default, &HashMap::new());
        assert!(config.contains("Generated by Corkscrew"));
    }

    #[test]
    fn test_detect_dxvk_version_missing_dll() {
        let dir = tempfile::tempdir().unwrap();
        assert!(detect_dxvk_version(dir.path()).is_none());
    }

    #[test]
    fn test_dx9_game_overrides() {
        let overrides = get_game_overrides("oblivion");
        assert!(overrides.contains_key("d3d9.maxFrameLatency"));
        assert_eq!(overrides.get("d3d9.maxFrameLatency").unwrap(), "1");
    }

    #[test]
    fn test_starfield_overrides() {
        let overrides = get_game_overrides("starfield");
        assert!(overrides.contains_key("dxvk.maxChunkSize"));
    }

    #[test]
    fn test_empty_hud_commented() {
        let config = generate_config("skyrimse", &DxvkPreset::Default, &HashMap::new());
        // Empty values should be commented out
        assert!(config.contains("# dxvk.hud ="));
    }

    #[test]
    fn test_config_deterministic() {
        let c1 = generate_config("skyrimse", &DxvkPreset::Default, &HashMap::new());
        let c2 = generate_config("skyrimse", &DxvkPreset::Default, &HashMap::new());
        assert_eq!(c1, c2);
    }
}
